def km(a_lat, a_lon, b_lat, b_lon):
    r = 6371.0
    p1, p2 = math.radians(a_lat), math.radians(b_lat)
    dp, dl = p2 - p1, math.radians(b_lon - a_lon)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def in_polygon(lat, lon):
    inside = False
    pts = POLY_POINTS
    for (y1, x1), (y2, x2) in zip(pts, pts[1:] + pts[:1]):
        if (y1 > lat) != (y2 > lat) and lon < x1 + (lat - y1) * (x2 - x1) / (y2 - y1):
            inside = not inside
    return inside


def zone_of(lat, lon):
    """(код, название). Z0 — вне зон: «в полигоне, вне зон» / «вне полигона» / «нет координат»."""
    if lat is None or lon is None:
        return "Z0", "нет координат"
    best = None
    for code, name, zlat, zlon, radius in ZONES:
        d = km(lat, lon, zlat, zlon)
        if d <= radius and (best is None or d < best[0]):
            best = (d, code, name)
    if best:
        return best[1], best[2]
    return ("Z0", "в полигоне, вне зон") if in_polygon(lat, lon) else ("Z0", "вне полигона")
